#!/usr/bin/env python3
"""rebase_on_push.py — resolve push-rejection via stash → pull --rebase → pop → push.

Encapsulates the exact recovery sequence from caretaker visit 536.
When a push is rejected because the remote has newer commits, this tool:

1. Stashes uncommitted changes (if any).
2. Pulls with --rebase to replay local commits on top of the remote.
3. Pops the stash (with optional --drop-stale to discard state-file
   conflicts that are regenerated by the writer process).
4. Pushes the rebased branch.

Usage:
    python3 tools/rebase_on_push.py                  # full sequence
    python3 tools/rebase_on_push.py --dry-run        # preview only
    python3 tools/rebase_on_push.py --drop-stale     # drop state-file stash conflicts
    python3 tools/rebase_on_push.py --max-retries 3  # retry push on network error
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional

STATE_FILES = {
    "data/writer_state.qwen.json",
    "data/commit_state.qwen.json",
    "data/writer_state.json",
    "data/commit_state.json",
}


@dataclass
class RebaseResult:
    success: bool
    stashed: bool = False
    stash_conflicts: List[str] = field(default_factory=list)
    rebase_conflicts: List[str] = field(default_factory=list)
    pushed: bool = False
    error: str = ""

    def to_dict(self) -> dict:
        return {
            "success": self.success,
            "stashed": self.stashed,
            "stash_conflicts": self.stash_conflicts,
            "rebase_conflicts": self.rebase_conflicts,
            "pushed": self.pushed,
            "error": self.error,
        }


def run(cmd: List[str], check: bool = False, **kwargs) -> subprocess.CompletedProcess:
    """Run a command, optionally raising on failure."""
    return subprocess.run(cmd, capture_output=True, text=True, check=check, **kwargs)


def has_dirty_tree() -> bool:
    """Check whether the working tree has uncommitted changes."""
    result = run(["git", "status", "--porcelain"])
    return bool(result.stdout.strip())


def create_stash() -> bool:
    """Stash uncommitted changes. Returns True if a stash was created."""
    result = run(["git", "stash"])
    return result.returncode == 0 and "No local changes" not in result.stdout


def pull_rebase(branch: str = "main", remote: str = "origin") -> tuple[bool, List[str]]:
    """Pull with --rebase. Returns (success, list of conflicted files)."""
    result = run(["git", "pull", "--rebase", remote, branch])
    if result.returncode == 0:
        return True, []
    conflicts = _parse_conflicts(result.stderr + result.stdout)
    # Abort the rebase to leave the repo clean
    run(["git", "rebase", "--abort"])
    return False, conflicts


def pop_stash(drop_stale: bool = False) -> tuple[bool, List[str]]:
    """Pop the stash. Returns (success, list of conflicted files)."""
    result = run(["git", "stash", "pop"])
    if result.returncode == 0:
        return True, []

    conflicts = _parse_conflicts(result.stdout + result.stderr)
    if drop_stale and all(f in STATE_FILES for f in conflicts):
        # All conflicts are in state files — safe to drop
        run(["git", "checkout", "--"] + list(conflicts))
        run(["git", "stash", "drop"])
        return True, conflicts

    return False, conflicts


def push(branch: str = "main", remote: str = "origin",
         max_retries: int = 1) -> tuple[bool, str]:
    """Push the current branch. Returns (success, error_message)."""
    for attempt in range(max_retries):
        result = run(["git", "push", remote, branch])
        if result.returncode == 0:
            return True, ""
        stderr = result.stderr
        if "rejected" in stderr:
            return False, f"push rejected (attempt {attempt + 1})"
        if "fatal" in stderr and attempt < max_retries - 1:
            continue  # network error, retry
        return False, stderr.strip()
    return False, "max retries exceeded"


def _parse_conflicts(output: str) -> List[str]:
    """Extract conflicted file paths from git output."""
    conflicts = []
    for line in output.splitlines():
        line = line.strip()
        if "CONFLICT" in line and ":" in line:
            # e.g. "CONFLICT (content): Merge conflict in docs/DEVLOG.md"
            parts = line.rsplit("in ", 1)
            if len(parts) == 2:
                conflicts.append(parts[1].strip())
        elif line.startswith("M ") or line.startswith("UU "):
            conflicts.append(line.split(None, 1)[1].strip())
    return sorted(set(conflicts))


def resolve_push_rejection(
    branch: str = "main",
    remote: str = "origin",
    dry_run: bool = False,
    drop_stale: bool = False,
    max_retries: int = 1,
) -> RebaseResult:
    """Execute the full stash → rebase → pop → push sequence."""
    result = RebaseResult(success=False)

    if dry_run:
        dirty = has_dirty_tree()
        result.success = True
        result.stashed = dirty
        result.error = "dry-run: no changes made"
        return result

    # Step 1: stash if needed
    if has_dirty_tree():
        if create_stash():
            result.stashed = True

    # Step 2: pull --rebase
    ok, conflicts = pull_rebase(branch, remote)
    if not ok:
        result.rebase_conflicts = conflicts
        result.error = f"rebase failed: {', '.join(conflicts) or 'unknown conflict'}"
        return result

    # Step 3: pop stash if we created one
    if result.stashed:
        ok, stash_conflicts = pop_stash(drop_stale=drop_stale)
        result.stash_conflicts = stash_conflicts
        if not ok:
            result.error = f"stash pop failed: {', '.join(stash_conflicts)}"
            return result

    # Step 4: commit any remaining changes
    if has_dirty_tree():
        run(["git", "add", "-A"])
        run(["git", "commit", "-m", "rebase_on_push: resolve and continue"])

    # Step 5: push
    ok, error = push(branch, remote, max_retries)
    result.pushed = ok
    result.success = ok
    if not ok:
        result.error = error

    return result


def main():
    parser = argparse.ArgumentParser(
        description="Resolve push rejection via stash-pull-rebase-pop-push"
    )
    parser.add_argument("--branch", default="main", help="Branch to push")
    parser.add_argument("--remote", default="origin", help="Remote name")
    parser.add_argument("--dry-run", action="store_true", help="Preview only")
    parser.add_argument("--drop-stale", action="store_true",
                        help="Drop stash conflicts in state files")
    parser.add_argument("--max-retries", type=int, default=1,
                        help="Max push retries on network error")
    parser.add_argument("--json", action="store_true", help="JSON output")
    args = parser.parse_args()

    result = resolve_push_rejection(
        branch=args.branch,
        remote=args.remote,
        dry_run=args.dry_run,
        drop_stale=args.drop_stale,
        max_retries=args.max_retries,
    )

    if args.json:
        print(json.dumps(result.to_dict(), indent=2))
    else:
        status = "OK" if result.success else "FAIL"
        print(f"[{status}] stashed={result.stashed} "
              f"rebase_conflicts={len(result.rebase_conflicts)} "
              f"stash_conflicts={len(result.stash_conflicts)} "
              f"pushed={result.pushed}")
        if result.error:
            print(f"  error: {result.error}")

    sys.exit(0 if result.success else 1)


if __name__ == "__main__":
    main()
